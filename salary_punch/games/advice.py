class AdviceView(tk.Frame):
    def __init__(self, master, *, width: int, height: int, on_back: Callable[[], None] | None = None):
        super().__init__(master, bg=BG, width=width, height=height)
        self.on_back = on_back
        self.pack_propagate(False)
        top = tk.Frame(self, bg=BG)
        top.pack(fill="x", padx=8, pady=(8, 4))
        tk.Label(top, text="人生建议书", bg=BG, fg=TEXT, font=("Microsoft YaHei UI", 10, "bold")).pack(side="left")
        tk.Label(top, text=f"{len(ADVICE)}条", bg=BG, fg=MUTED, font=("Microsoft YaHei UI", 8)).pack(side="left", padx=6)
        tk.Button(top, text="← 薪资", command=self._back, bg=ACCENT, fg="#1A1400", relief="flat",
                  font=("Microsoft YaHei UI", 8), padx=6, cursor="hand2").pack(side="right")
        self.card = tk.Label(
            self, text="点下面，抽一条给现在的自己", bg=CARD, fg=TEXT, wraplength=width - 40,
            justify="left", font=("Microsoft YaHei UI", 11), padx=14, pady=18,
        )
        self.card.pack(fill="both", expand=True, padx=12, pady=8)
        tk.Button(
            self, text="翻一页建议", command=self._draw, bg=ACCENT, fg="#1A1400", relief="flat",
            font=("Microsoft YaHei UI", 9, "bold"), padx=12, pady=4, cursor="hand2",
        ).pack(pady=(0, 12))

    def _back(self):
        if self.on_back:
            self.on_back()

    def destroy_game(self):
        self.destroy()

    def _draw(self):
        self.card.configure(text=random.choice(ADVICE))
